# Writes lib/parity/recharts/charts.tsrx: the two charts the dashboard draws, as recharts renders them, with
# every element in place on the server. public/parity/recharts.js only sets geometry and the y-axis labels:
# Markless resumes by counting elements in document order, so a script that adds elements breaks it.
import sys

def z(n, inner=''):
    return '<g tabindex="-1" class="recharts-zIndex-layer_%s">%s</g>' % (n, inner)

def axis(kind, n):
    ticks = ''.join('<g class="recharts-layer recharts-cartesian-axis-tick"></g>' for _ in range(n))
    return '<g class="recharts-layer recharts-cartesian-axis recharts-%sAxis %sAxis"><g class="recharts-cartesian-axis-ticks recharts-%sAxis-ticks"><g class="recharts-cartesian-axis-tick-lines recharts-%sAxis-tick-lines">%s</g></g></g>' % (kind, kind, kind, kind, ticks)

def x_labels(names):
    return '<g class="recharts-cartesian-axis-tick-labels recharts-xAxis-tick-labels">' + ''.join(
        '<g class="recharts-layer recharts-cartesian-axis-tick-label"><text stroke="none" font-size="12" height="30" orientation="bottom" class="recharts-text recharts-cartesian-axis-tick-value" text-anchor="middle" fill="#888888"><tspan dy="0.71em">%s</tspan></text></g>' % n for n in names) + '</g>'

def y_labels(n, ltr):
    d = ' direction="ltr"' if ltr else ''
    return '<g class="recharts-cartesian-axis-tick-labels recharts-yAxis-tick-labels">' + ''.join(
        '<g class="recharts-layer recharts-cartesian-axis-tick-label"><text%s stroke="none" font-size="12" orientation="left" width="60" class="recharts-text recharts-cartesian-axis-tick-value" text-anchor="end" fill="#888888"><tspan dy="0.355em"></tspan></text></g>' % d for _ in range(n)) + '</g>'

def surface(key, height, clip, body):
    return ('<div class="recharts-responsive-container" style="width: 100%%; height: %dpx; min-width: 0px;" data-parity-chart="%s">'
            '<div style="width: 0px; overflow-x: visible;">'
            '<div width="0" height="%d" class="recharts-wrapper" style="position: relative; cursor: default; width: 0px; height: %dpx;">'
            '<svg role="application" tabindex="0" class="recharts-surface" width="0" height="%d" viewBox="0 0 0 %d" style="width: 100%%; height: 100%%; display: block;">'
            '<title></title><desc></desc>%s%s<defs><clipPath id="%s"><rect x="65" y="5" height="%d" width="0" /></clipPath></defs>%s'
            '</svg></div></div></div>') % (height, key, height, height, height, height, z(-100), z(-50), clip, height - 40, body)

months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun']

bars = ''.join('<g class="recharts-layer recharts-bar-rectangle"><g class="recharts-layer recharts-inactive-bar"><path fill="currentColor" class="recharts-rectangle fill-primary" name="%s" /></g></g>' % m for m in months)
overview = surface('overview', 350, 'recharts1-clip',
    z(100) + z(200) + z(300, '<g class="recharts-layer recharts-bar fill-primary" id="recharts-bar-1"><g class="recharts-layer recharts-bar-rectangles"><g class="recharts-layer">%s</g></g></g>' % bars)
    + z(400) + z(500, axis('x', 12) + axis('y', 5)) + z(600) + z(1000) + z(1100) + z(1200) + z(2000, x_labels(months) + y_labels(5, True)))

def area(cls, opacity, n):
    return ('<g class="recharts-layer recharts-area %s"><g class="recharts-layer"><defs><clipPath id="animationClipPath-recharts-area-%d"><rect x="65" y="0" width="0" height="266" /></clipPath></defs>'
            '<g class="recharts-layer" clip-path="url(#animationClipPath-recharts-area-%d)"><g class="recharts-layer">'
            '<path class="recharts-curve recharts-area-area" stroke-width="1" fill="currentColor" fill-opacity="%s" height="260" stroke="none" id="recharts-area-%d" />'
            '<path class="recharts-curve recharts-area-curve" stroke-width="1" fill="none" fill-opacity="%s" height="260" stroke="currentColor" />'
            '</g></g></g></g>') % (cls, n, n, opacity, n, opacity)

analytics = surface('analytics', 300, 'recharts2-clip',
    z(100, area('text-primary', '0.15', 1) + area('text-muted-foreground', '0.1', 2)) + z(200) + z(300) + z(400)
    + z(500, axis('x', 7) + axis('y', 5)) + z(600) + z(1000) + z(1100) + z(1200) + z(2000, x_labels(days) + y_labels(5, False)))

out = '''// Parity port of recharts for the dashboard: the BarChart (overview.tsx) and AreaChart (analytics-chart.tsx)
// with exactly the props those files pass (XAxis dataKey name, stroke #888888, fontSize 12, no tick or axis
// lines; Bar radius [4, 4, 0, 0]; two monotone Areas). Generated by deploy/shadcn-admin/scripts/gen-charts.py.
// The data is drawn from Math.random in the browser, as the old modules did, and public/parity/recharts.js
// lays the chart out when the page loads.

export function OverviewChart() @{
	%s
}

export function AnalyticsChart() @{
	%s
}
''' % (overview, analytics)
open(sys.argv[1], 'w').write(out)
