// A join the ledger finds may be another component's element: a weaker match is reported, a missing stronger one still fails.
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { after, before, test } from 'node:test';
import { buildLedger, type Ledger } from '../src/ledger/index.ts';

const SWITCHER = 'registry/bases/base/blocks/sidebar-01/components/version-switcher.tsx';
const SOURCE: Record<string, string> = {
	'package.json': '{}',
	'components/ui/popover.tsx': `import { Popover as P } from "radix-ui"
export function Popover(props) { return <P.Root data-slot="popover" {...props} /> }
export function PopoverTrigger(props) { return <P.Trigger data-slot="popover-trigger" {...props} /> }
export function PopoverContent(props) { return <P.Portal><P.Content data-slot="popover-content" {...props} /></P.Portal> }`,
	[SWITCHER]: `"use client"
import * as React from "react"
export function VersionSwitcher() {
  const [version, setVersion] = React.useState("1")
  return <button type="button" onClick={() => { setVersion("2") }}>Version two</button>
}`,
	'components/date-field.tsx': `"use client"
import * as React from "react"
import { Popover, PopoverContent, PopoverTrigger } from "@/components/ui/popover"
export function DateField() {
  const [day, setDay] = React.useState(0)
  return (
    <Popover>
      <PopoverTrigger>Pick a day</PopoverTrigger>
      <PopoverContent><button type="button" onClick={() => { setDay(1) }} /></PopoverContent>
    </Popover>
  )
}`,
	'components/mobile-nav.tsx': `"use client"
import * as React from "react"
import { Popover, PopoverContent, PopoverTrigger } from "@/components/ui/popover"
export function MobileNav() {
  const [open, setOpen] = React.useState(false)
  return (
    <Popover open={open} onOpenChange={setOpen}>
      <PopoverTrigger>Toggle Menu</PopoverTrigger>
      <PopoverContent>
        <div>Sections</div>
        <a href="/docs" onClick={() => { setOpen(false) }}><span title="New" /></a>
      </PopoverContent>
    </Popover>
  )
}`,
};

const page = (route: string, body: string) => `// Generated by markless-migrate convert from the old site; change the converter, not this file. (${route})
import { behave } from '../../../../lib/parts/index.ts';
export default function Page() @{
	<><main onClick={(event) => behave(event)}>${body}</main></>
}
`;
const PARTS: Record<string, string> = {
	'lib/parts/index.ts': `export function behave() {}\n`,
	'lib/parts/registry.ts': `import { SITE_PARTS } from '../site/parts.ts';\nexport const PARTS = [...SITE_PARTS];\n`,
	'lib/site/parts.ts': `export const SITE_PARTS = [];\n`,
};
// The docs page's own switcher and sidebar: the same text as the registry example's button and the mobile nav's link.
const POPOVER = page('/docs/components/base/popover', '<button type="button">Version two</button><button data-slot="popover-trigger" type="button">Pick a day</button><nav><div>Sections</div><a data-slot="sidebar-menu-button" href="/docs"><span title="New"></span></a></nav>');
const SIDEBAR = page('/docs/components/base/sidebar', '<p>Sidebar</p>');
const IN_LAYER = page('/docs/components/base/popover', '<div role="dialog" data-mm-layer="menu" hidden><div>Sections</div><a href="/docs"><span title="New"></span></a></div>');

const inventory = (routes: readonly string[], moved: readonly string[] = []) => JSON.stringify({ version: 1, origin: 'http://old', generatedAt: '', limit: 0, truncated: false, routes: [...routes.map((route) => ({ route, status: 200 })), ...moved.map((route) => ({ route, status: 308, redirectsTo: '/docs' }))], locales: [], localeRouting: { prefixes: [], negotiation: {} } });
const ROUTES = ['/docs/components/base/popover', '/docs/components/base/sidebar'];

async function write(root: string, files: Record<string, string>): Promise<void> {
	for (const [file, text] of Object.entries(files)) {
		await mkdir(dirname(join(root, file)), { recursive: true });
		await writeFile(join(root, file), text);
	}
}

let dir: string;
const ledgers: Record<string, Ledger> = {};
before(async () => {
	dir = await mkdtemp(join(tmpdir(), 'ledger-weaker-match-'));
	const source = join(dir, 'source');
	await write(source, SOURCE);
	const apps: Record<string, { pages: Record<string, string>; routes: readonly string[]; moved?: readonly string[] }> = {
		few: { pages: { 'pages/docs/components/base/popover.tsrx': POPOVER }, routes: ROUTES },
		whole: { pages: { 'pages/docs/components/base/popover.tsrx': POPOVER, 'pages/docs/components/base/sidebar.tsrx': SIDEBAR }, routes: ROUTES },
		layered: { pages: { 'pages/docs/components/base/popover.tsrx': IN_LAYER }, routes: ROUTES },
		redirected: { pages: { 'pages/docs/components/base/popover.tsrx': POPOVER }, routes: [ROUTES[0]!], moved: [ROUTES[1]!] },
	};
	for (const [name, { pages, routes, moved }] of Object.entries(apps)) {
		const app = join(dir, name);
		await write(app, { ...PARTS, ...pages, '.migrate/inventory.json': inventory(routes, moved) });
		ledgers[name] = await buildLedger({ source, app, workers: 1 });
	}
});
after(() => rm(dir, { recursive: true, force: true }));

const entry = (l: Ledger, file: string, prop: string) => l.entries.find((e) => e.site.file === file && e.site.props.includes(prop) && e.site.element !== 'Popover');
const failsOn = (l: Ledger, text: string) => l.failures.filter((f) => f.check.includes(text));

test("an example found on a route sharing fewer of its path's words than a route the app was not converted for is a guess", () => {
	assert.equal(entry(ledgers.few!, SWITCHER, 'onClick')?.verdict, 'weak');
	assert.deepEqual(failsOn(ledgers.few!, 'Version two'), []);
});

test('an example missing from the converted route that is its own still fails where it was found instead', () => {
	assert.equal(entry(ledgers.whole!, SWITCHER, 'onClick')?.verdict, 'unmapped');
	assert.equal(failsOn(ledgers.whole!, 'Version two').length, 1);
});

test('a route that only redirects is no page of its own the example could have been found on', () => {
	assert.equal(entry(ledgers.redirected!, SWITCHER, 'onClick')?.verdict, 'unmapped');
});

test("a control the source renders only inside a popover's content, found only outside every layer of the port, is a guess", () => {
	assert.equal(entry(ledgers.few!, 'components/mobile-nav.tsx', 'onClick')?.verdict, 'weak');
	assert.deepEqual(failsOn(ledgers.few!, 'New'), []);
});

test("a control in a popover's content found by the trigger beside it is joined on that trigger, which is outside the layer", () => {
	const found = entry(ledgers.few!, 'components/date-field.tsx', 'onClick');
	assert.equal(found?.site.anchors[0]?.anchor, 'near');
	assert.equal(found?.verdict, 'unmapped');
});

test('the same control found inside a layer is joined there as before', () => {
	const found = entry(ledgers.layered!, 'components/mobile-nav.tsx', 'onClick');
	assert.ok(found?.port && found.verdict !== 'weak', `joined, not a guess: ${found?.verdict}`);
});
