// A page's own component found in an app converted for a few routes (dev, fix): the site's other routes, not the
// app's pages, say whether the component has a page of its own it should have been found on.
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { after, before, test } from 'node:test';
import { buildLedger, type Ledger } from '../src/ledger/index.ts';

const SOURCE: Record<string, string> = {
	'package.json': '{}',
	'components/ui/button.tsx': `import { Button as B } from "@base-ui/react/button"
export function Button(props) { return <B data-slot="button" {...props} /> }`,
	'app/(app)/(create)/components/open-preset.tsx': `"use client"
import * as React from "react"
import { Button } from "@/components/ui/button"
export function OpenPreset() {
  const [input, setInput] = React.useState("")
  return (
    <form onSubmit={(event) => { event.preventDefault(); setInput("") }}>
      <Button type="submit">Open</Button>
    </form>
  )
}`,
};

// The charts page's "Open in v0" link: a Button rendered as a link, whose text holds the preset form's "Open".
const PORT: Record<string, string> = {
	'pages/charts/area.tsrx': `// Generated by markless-migrate convert from the old site; change the converter, not this file. (/charts/area)
import { behave } from '../../lib/parts/index.ts';
export default function Page() @{
	<><main onClick={(event) => behave(event)}><a data-slot="button" href={"https://v0.dev/chat/api/open?url=" + url}>Open in v0</a></main></>
}
`,
	'lib/parts/index.ts': `export function behave() {}\n`,
	'lib/parts/registry.ts': `import { SITE_PARTS } from '../site/parts.ts';\nexport const PARTS = [...SITE_PARTS];\n`,
	'lib/site/parts.ts': `export const SITE_PARTS = [];\n`,
};

const inventory = (routes: readonly string[]) => JSON.stringify({ version: 1, origin: 'http://old', generatedAt: '', limit: 0, truncated: false, routes: routes.map((route) => ({ route, status: 200 })), locales: [], localeRouting: { prefixes: [], negotiation: {} } });

async function write(root: string, files: Record<string, string>): Promise<void> {
	for (const [file, text] of Object.entries(files)) {
		await mkdir(dirname(join(root, file)), { recursive: true });
		await writeFile(join(root, file), text);
	}
}

let dir: string;
const ledgers: Record<string, Ledger> = {};
before(async () => {
	dir = await mkdtemp(join(tmpdir(), 'ledger-site-routes-'));
	const source = join(dir, 'source');
	await write(source, SOURCE);
	for (const [name, routes] of [['one', ['/charts/area']], ['site', ['/charts/area', '/create']]] as const) {
		const app = join(dir, name);
		await write(app, { ...PORT, '.migrate/inventory.json': inventory(routes) });
		ledgers[name] = await buildLedger({ source, app, workers: 1 });
	}
});
after(() => rm(dir, { recursive: true, force: true }));

const submit = (l: Ledger) => l.entries.find((e) => e.site.file.endsWith('open-preset.tsx') && e.site.props.includes('onSubmit'));

test("a page's own component found only on a route that is not its page is a guess, though the app holds only that route", () => {
	assert.equal(submit(ledgers.site!)?.verdict, 'weak');
	assert.deepEqual(ledgers.site!.failures, []);
});

test('a site whose routes are all unrelated to the component keeps the join it found', () => {
	assert.equal(submit(ledgers.one!)?.verdict, 'unmapped');
});
