import { execFile } from 'node:child_process';
import { copyFile, readFile, stat } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const DUMP = fileURLToPath(new URL('./dump.mjs', import.meta.url));
const run = promisify(execFile);

/** A fumadocs-mdx collection file, rewritten to read its entries as data: what the old route handlers import, minus the content's components. */
export interface FumadocsCollection {
	/** The collection file's path in the old app (`.source/server.ts`). */
	readonly file: string;
	/** Its replacement, importing `./collection.json` and `./fumadocs-runtime.mjs`. */
	readonly source: string;
	readonly data: string;
	readonly entries: number;
	/** Copies fumadocs-mdx's runtime (plain Node code) next to the replacement. */
	copyRuntime(dir: string): Promise<void>;
}

/**
 * When the old app's content goes through fumadocs-mdx (a `.source/server.ts` the route handlers import), runs
 * fumadocs-mdx's own Node loader over it at convert time and keeps each entry's literal exports (frontmatter,
 * structuredData, extracted references; a toc of JSX is left out), so the handlers' own code reads the same collection
 * without the content's React components.
 */
export async function fumadocsCollection(source: string): Promise<FumadocsCollection | undefined> {
	const file = '.source/server.ts';
	const text = await readFile(join(source, file), 'utf8').catch(() => undefined);
	if (!text || !/from ['"]fumadocs-mdx\/runtime\/server['"]/.test(text)) return undefined;
	const { stdout } = await run(process.execPath, [DUMP, file], { cwd: source, maxBuffer: 256 * 1024 * 1024 });
	const data = JSON.parse(stdout) as Record<string, Record<string, unknown>>;
	const rewritten = text
		.replace(/^\/\/ @ts-nocheck\n/, '')
		.replace(/^import \* as (__fd_glob_\d+) from "[^"]+"$/gm, 'const $1 = COLLECTION.$1;')
		.replace(/^import \{ default as (__fd_glob_\d+) \} from "[^"]+"$/gm, 'const $1 = COLLECTION.$1.default;')
		.replace(/^import \{ server \} from 'fumadocs-mdx\/runtime\/server';$/m, "import { server } from './fumadocs-runtime.mjs';")
		.replace(/^import type .*$/gm, '')
		.replace(/server<[\s\S]*?>\(/, 'server(');
	const header = `// Generated by markless-migrate convert from the old app's ${file}: each entry read as data at convert time by fumadocs-mdx's own loader.\n// @ts-nocheck\nimport COLLECTION from './collection.json' with { type: 'json' };\n`;
	const fromApp = createRequire(join(source, 'package.json'));
	const runtime = fromApp.resolve('fumadocs-mdx/runtime/server');
	return {
		file,
		source: header + rewritten,
		data: JSON.stringify(data),
		entries: Object.keys(data).length,
		async copyRuntime(dir) {
			await copyFile(runtime, join(dir, 'fumadocs-runtime.mjs'));
			if (!(await stat(join(dirname(runtime), '..', '..', 'LICENSE')).catch(() => undefined))) return;
			await copyFile(join(dirname(runtime), '..', '..', 'LICENSE'), join(dir, 'fumadocs-mdx.LICENSE'));
		},
	};
}
