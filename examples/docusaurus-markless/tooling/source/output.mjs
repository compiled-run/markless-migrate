// Every <head> element of every route, matched up into one list of slots document.tsrx can write
// (document.tsrx renders a fixed list; a route without an element leaves its slot empty).
const IDENTITY = ['name', 'property', 'rel', 'hreflang', 'type', 'title', 'charset'];
const slotKey = ({ tag, attrs }) => `${tag}|${IDENTITY.map((n) => `${n}=${attrs[n] ?? ''}`).join('|')}`;
const nodeToEntry = (node) => ({ tag: node.tag, attrs: Object.fromEntries(node.attrs), text: node.children.join('') });

export async function writeHeads(pages, staticHead, bodyPrefix, staticPages = []) {
	const slots = [];
	const seen = new Map();
	const perRoute = {};
	for (const [path, page] of pages) {
		const entries = page.head.map(nodeToEntry);
		const counts = new Map();
		const values = [];
		let title = '';
		let ld = '';
		for (const entry of entries) {
			if (entry.tag === 'title') {
				title = entry.text;
				continue;
			}
			const base = slotKey(entry);
			const n = counts.get(base) ?? 0;
			counts.set(base, n + 1);
			const key = `${base}#${n}`;
			if (!seen.has(key)) {
				seen.set(key, slots.length);
				slots.push({ tag: entry.tag, attrs: new Set() });
			}
			const index = seen.get(key);
			for (const name of Object.keys(entry.attrs)) slots[index].attrs.add(name);
			values[index] = entry.attrs;
			if (entry.tag === 'script') ld = entry.text;
		}
		perRoute[path] = { title, ld, class: page.htmlClasses.join(' '), slots: slots.map((_, i) => values[i] ?? null) };
	}
	for (const route of Object.values(perRoute)) route.slots = slots.map((_, i) => route.slots[i] ?? null);
	await writeFile(join(app, 'lib/head-slots.json'), `${JSON.stringify(perRoute)}\n`);
	const slotLines = slots
		.map((slot, index) => {
			const attrs = [...slot.attrs].map((name) => ` ${name}={s[${index}]?.[${JSON.stringify(name)}]}`).join('');
			return slot.tag === 'script' ? `\t\t\t<script${attrs}>{head.ld}</script>` : `\t\t\t<${slot.tag}${attrs} />`;
		})
		.join('\n');
	const staticLines = toTsrx(staticHead, 3);
	const plainHeads = [];
	const plainRoutes = {};
	for (const page of staticPages) {
		const key = JSON.stringify(page.head);
		let index = plainHeads.findIndex((nodes) => JSON.stringify(nodes) === key);
		if (index < 0) index = plainHeads.push(page.head) - 1;
		plainRoutes[page.path] = index;
	}
	const indent = (text) => text.replace(/^(?=.)/gm, '\t');
	await writeFile(
		join(app, 'document.tsrx'),
		`${HEADER}
// Each route's <head> as the old site's theme writes it (lib/head-slots.json), the tags its plugins add to every page,
// and the start of <body>: the SVG sprite and the colour-mode script the theme runs before the page paints.
import type { Children } from '@markless/core';
import { Html } from '@markless/router';
import heads from './lib/head-slots.json';

type Slot = Readonly<Record<string, string>> | null;
const routes = heads as unknown as Record<string, { readonly title: string; readonly ld: string; readonly class: string; readonly slots: readonly Slot[] }>;
// The old site's static HTML files, each with its own <head> (one of the blocks below) and none of the theme's.
const plainRoutes: Readonly<Record<string, number>> = ${JSON.stringify(plainRoutes)};

export default function Document({ url, children }: { readonly url?: { readonly pathname: string }; readonly children?: Children }) @{
	const path = (url?.pathname ?? '/').replace(/^\\/__not-found(?=\\/)/, '').replace(/\\/$/, '') || '/';
	const found = routes[path] ?? routes[decodeURIComponent(path)];
	const head = found ?? routes['/404']!;
	// The not-found page's head names the address it was asked for, as the theme writes it once the page has started.
	const s = found ? head.slots : head.slots.map((slot) => slot && Object.fromEntries(Object.entries(slot).map(([name, value]) => [name, value.replace(/\\/404\\.html$/, path)])));

	const plain = plainRoutes[path] ?? plainRoutes[decodeURIComponent(path)];

	<Html lang={plain === undefined ? 'en' : undefined} dir={plain === undefined ? 'ltr' : undefined} class={plain === undefined && head.class ? head.class : undefined}>
		<head>
			@if (plain === undefined) {
				<>
${indent(`			<meta charset="UTF-8" />
			<title>{head.title}</title>
${slotLines}
${staticLines}			<link rel="stylesheet" href="/assets/css/${stylesheetName}" />
			<link rel="stylesheet" href="/mm-site.css" />
			<script>{${JSON.stringify(DOCSEARCH_SCRIPT)}}</script>
			<script>{${JSON.stringify(SEARCH_INTENT_SCRIPT)}}</script>
`)}				</>
			}
${plainHeads.map((nodes, i) => `			@if (plain === ${i}) {\n				<>\n${toTsrx(nodes, 5)}				</>\n			}\n`).join('')}		</head>
		<body>
			@if (plain === undefined) {
				<>
${toTsrx(bodyPrefix, 5)}				</>
			}
			{children}
		</body>
	</Html>
}
`,
	);
}

// The tags the old site's plugins add to every page (feeds, search description, PWA metadata, stylesheets) and
// the body prefix, from the same plugin hooks Docusaurus reads; the analytics tags are left out.
export function pluginHtmlTags(site) {
	const { loadHtmlTags } = siteRequire('@docusaurus/core/lib/server/htmlTags.js');
	const tags = loadHtmlTags({ plugins: site.plugins, router: site.context.siteConfig.future.experimental_router });
	const head = parseHtml(tags.headTags).filter((n) => typeof n !== 'string' && !(n.tag === 'script' && (n.attrs.some(([k, v]) => k === 'src' && v.includes('googletagmanager')) || n.children.join('').includes('gtag('))));
	const stylesheets = site.context.siteConfig.stylesheets.map((s) => ({ tag: 'link', attrs: [['rel', 'stylesheet'], ['href', s.href], ...(s.type ? [['type', s.type]] : [])], children: [] }));
	const known = new Set(head.map((n) => JSON.stringify(n.attrs)));
	const body = parseHtml(tags.preBodyTags).filter((n) => typeof n !== 'string');
	return { head: [...head, ...stylesheets.filter((n) => !known.has(JSON.stringify(n.attrs)))], body };
}

// Files: the site's static directories as the old build copies them, and the assets the pages reference.
export async function copyFiles(site, pageFiles = []) {
	const publicDir = join(app, 'public');
	for (const dir of site.context.siteConfig.staticDirectories) {
		const from = join(website, dir.startsWith('/') ? relative(website, dir) : dir);
		await cp(from, publicDir, { recursive: true, force: true }).catch(() => undefined);
	}
	// The static HTML files are Markless pages now (staticHtmlPages).
	for (const file of pageFiles) await rm(join(publicDir, file), { force: true });
	for (const [url, path] of emitted) {
		await mkdir(dirname(join(publicDir, url)), { recursive: true });
		await cp(path, join(publicDir, decodeURIComponent(url)));
	}
	for (const [url, base64] of idealFiles) {
		await mkdir(dirname(join(publicDir, url)), { recursive: true });
		await writeFile(join(publicDir, url), Buffer.from(base64, 'base64'));
	}
	await mkdir(join(publicDir, 'assets/css'), { recursive: true });
	for (const file of await readdir(join(website, 'build/assets/css'))) if (file === stylesheetName) await cp(join(website, 'build/assets/css', file), join(publicDir, 'assets/css', file));
}

// What lib/site.ts needs to do in the browser what the theme does there: each docs sidebar (to render a category's
// items when it is first opened), the class names those items use, and the code blocks' light and dark colours.
export async function writeClientData(site, pages) {
	const { cssModuleMap } = await import('./stylesheet.mjs');
	const theme = join(website, '../packages/docusaurus-theme-classic/src/theme');
	const sidebars = {};
	for (const plugin of site.plugins.filter((p) => p.name === 'docusaurus-plugin-content-docs')) {
		for (const version of plugin.content?.loadedVersions ?? []) {
			const { readGenerated } = await import('./site.mjs');
			const route = site.routes.find((r) => r.ancestors.some((a) => a.context?.data?.docsVersion?.includes(`/${plugin.options.id}/version-${version.versionName}`)));
			if (!route) continue;
			const data = await readGenerated(site.context, route.ancestors.find((a) => a.context?.data?.docsVersion).context.data.docsVersion);
			for (const [name, items] of Object.entries(data.docsSidebars)) sidebars[`${data.pluginId}:${name}`] = items;
		}
	}
	const link = cssModuleMap(join(theme, 'DocSidebarItem/Link/styles.module.css'));
	const category = cssModuleMap(join(theme, 'DocSidebarItem/Category/styles.module.css'));
	const external = cssModuleMap(join(theme, 'Icon/ExternalLink/styles.module.css'));
	const classes = { linkLabel: link.linkLabel, menuExternalLink: link.menuExternalLink, categoryLink: category.categoryLink, categoryLinkLabel: category.categoryLinkLabel, iconExternalLink: external.iconExternalLink };
	const files = {};
	await rm(join(app, 'public/sidebars'), { recursive: true, force: true });
	await mkdir(join(app, 'public/sidebars'), { recursive: true });
	for (const [key, items] of Object.entries(sidebars)) {
		const json = JSON.stringify(items);
		files[key] = `/sidebars/${key.replace(/[^\w-]/g, '-')}.${createHash('sha256').update(json).digest('hex').slice(0, 10)}.json`;
		await writeFile(join(app, 'public', files[key]), json);
	}
	await writeFile(join(app, 'lib/sidebars.json'), `${JSON.stringify({ classes, files, trailingSlash: site.context.siteConfig.trailingSlash })}\n`);
	// The theme's CSS modules lib/site.ts toggles classes of, with their built names.
	const modules = ['CodeBlock/Buttons', 'CodeBlock/Buttons/CopyButton', 'CodeBlock/Buttons/WordWrapButton', 'ColorModeToggle', 'Navbar/Content', 'Navbar/Layout', 'Navbar/Search', 'BackToTopButton', 'SkipToContent', 'AnnouncementBar', 'TOC', 'TOCCollapsible', 'TOCCollapsible/CollapseButton', 'DocItem/TOC/Mobile', 'DocRoot/Layout/Main', 'DocRoot/Layout/Sidebar', 'DocRoot/Layout/Sidebar/ExpandButton', 'DocSidebar/Desktop', 'DocSidebar/Desktop/Content', 'DocSidebar/Desktop/CollapseButton', 'NavbarItem/DropdownNavbarItem/Mobile', 'Tabs', 'TabItem', 'BlogSidebar/Mobile'];
	const themeClasses = Object.fromEntries(modules.map((dir) => [dir, cssModuleMap(join(theme, dir, 'styles.module.css'))]));
	themeClasses.ThemedComponent = cssModuleMap(join(website, '../packages/docusaurus-theme-common/src/components/ThemedComponent/styles.module.css'));
	themeClasses.Details = cssModuleMap(join(website, '../packages/docusaurus-theme-common/src/components/Details/styles.module.css'));
	themeClasses.SearchPage = cssModuleMap(join(website, '../packages/docusaurus-theme-search-algolia/src/theme/SearchPage/styles.module.css'));
	themeClasses.APITable = cssModuleMap(join(website, 'src/components/APITable/styles.module.css'));
	themeClasses.ChangelogAuthors = cssModuleMap(join(website, 'src/plugins/changelog/theme/ChangelogItem/Header/Authors/styles.module.css'));
	themeClasses.ChangelogAuthor = cssModuleMap(join(website, 'src/plugins/changelog/theme/ChangelogItem/Header/Author/styles.module.css'));
	themeClasses.ErrorBoundary = cssModuleMap(join(website, '../packages/docusaurus-theme-common/src/utils/errorBoundaryUtils.module.css'));
	themeClasses.ColorGenerator = cssModuleMap(join(website, 'src/components/ColorGenerator/styles.module.css'));
	await writeFile(join(app, 'lib/theme-classes.json'), `${JSON.stringify(themeClasses, null, '\t')}\n`);
	// What the navbar's doc links and version dropdowns need to follow a reader's preferred docs version.
	const navbarItems = (items) => items.flatMap((item) => [item, ...navbarItems(item.items ?? [])]);
	const docItems = navbarItems(site.context.siteConfig.themeConfig.navbar.items).filter((item) => item?.type === 'doc');
	const docsData = site.globalData['docusaurus-plugin-content-docs'] ?? {};
	const docsVersions = Object.fromEntries(
		Object.entries(docsData).map(([pluginId, plugin]) => {
			const docIds = docItems.filter((item) => (item.docsPluginId ?? 'default') === pluginId).map((item) => item.docId);
			return [
				pluginId,
				{ path: plugin.path, versions: plugin.versions.map((version) => ({
					name: version.name,
					label: version.label,
					isLast: version.isLast,
					path: version.path,
					mainDoc: version.docs.find((doc) => doc.id === version.mainDocId)?.path,
					docs: Object.fromEntries(docIds.map((id) => [id, version.docs.find((doc) => doc.id === id)?.path]).filter(([, path]) => path)),
					sidebars: Object.fromEntries(Object.entries(version.sidebars ?? {}).map(([id, sidebar]) => [id, sidebar.link?.path]).filter(([, path]) => path)),
				})) },
			];
		}),
	);
	await (await import('./interactive-data.mjs')).writeInteractiveData(app);
	await writeFile(join(app, 'lib/docs-versions.json'), `${JSON.stringify(docsVersions)}\n`);
	const { prism } = site.context.siteConfig.themeConfig;
	await writeFile(join(app, 'lib/prism-themes.json'), `${JSON.stringify({ light: prism.theme, dark: prism.darkTheme })}\n`);
	void pages;
}

// The files the old site's plugins write after its pages are built (the sitemap, the blog and changelog feeds,
// the client-side redirect pages), made by those same plugin hooks from the pages rendered here.
// Where `docusaurus build` writes a route's page: a path that already ends in .html is that file.
const htmlFile = (path) => (path === '/' ? 'index.html' : path.endsWith('.html') ? path.slice(1) : `${path.slice(1)}.html`);
export async function runPostBuild(site, pages) {
	const { toHtml } = await import('./h.mjs');
	const { readGenerated } = await import('./site.mjs');
	const staging = join(import.meta.dirname, '../.cache/build');
	await rm(staging, { recursive: true, force: true });
	const routesBuildMetadata = {};
	for (const route of site.routes) {
		const path = route.path.length > 1 ? route.path.replace(/\/$/, '') : route.path;
		const page = pages.get(path);
		let noIndex = page ? page.head.some((n) => n.tag === 'meta' && n.attrs.some(([k, v]) => k === 'name' && v.toLowerCase() === 'robots') && n.attrs.some(([k, v]) => k === 'content' && /noindex/i.test(v))) : false;
		const versionRoute = route.ancestors.find((a) => a.context?.data?.docsVersion);
		if (!page && versionRoute) noIndex = (await readGenerated(site.context, versionRoute.context.data.docsVersion)).noIndex;
		routesBuildMetadata[route.path] = { noIndex };
		if (page) {
			const file = htmlFile(path);
			await mkdir(dirname(join(staging, file)), { recursive: true });
			await writeFile(join(staging, file), `<!DOCTYPE html><html><head>${toHtml(page.head)}</head><body>${toHtml(page.feedBody ?? page.body)}</body></html>`);
		}
	}
	const { getRoutesPaths } = siteRequire('@docusaurus/core/lib/server/routes.js');
	const props = { ...site.context, outDir: staging, routes: site.routeTree, routesPaths: getRoutesPaths(site.routeTree, site.context.baseUrl), plugins: site.plugins };
	const hooks = ['docusaurus-plugin-sitemap', 'docusaurus-plugin-content-blog', 'changelog-plugin', 'docusaurus-plugin-client-redirects'];
	for (const plugin of site.plugins.filter((p) => hooks.includes(p.name) && p.postBuild)) {
		await plugin.postBuild({ ...props, routesBuildMetadata, content: plugin.content, head: {} });
	}
	// Everything they wrote that is not one of the pages themselves goes to public/.
	const written = [];
	const walk = async (dir) => {
		for (const entry of await readdir(dir, { withFileTypes: true })) {
			const full = join(dir, entry.name);
			if (entry.isDirectory()) await walk(full);
			else written.push(relative(staging, full));
		}
	};
	await walk(staging);
	const pageFiles = new Set([...pages.keys()].map(htmlFile));
	// `x.html.html` redirects only shadow `x.html` itself, which the old site serves as the page: left out.
	for (const file of written.filter((f) => !pageFiles.has(f) && !f.endsWith('.html.html'))) {
		await mkdir(dirname(join(app, 'public', file)), { recursive: true });
		await cp(join(staging, file), join(app, 'public', file));
	}
	return written.filter((f) => !pageFiles.has(f));
}
