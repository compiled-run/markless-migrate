// /docs/advanced is a page and the parent of /docs/advanced/architecture, so it is pages/docs/advanced/index.tsrx.
export function pageFile(path, allPaths) {
	if (path === '/') return join(app, 'pages/index.tsrx');
	const isParent = allPaths.some((other) => other.startsWith(`${path}/`));
	return join(app, 'pages', ...(isParent ? [...path.slice(1).split('/'), 'index.tsrx'] : [`${path.slice(1)}.tsrx`]));
}

const isFooter = (node) => typeof node !== 'string' && node.tag === 'footer' && node.attrs.some(([n, v]) => n === 'class' && v.includes('theme-layout-footer'));

export async function writeFooter(footer) {
	const file = join(app, 'components/generated/footer.tsrx');
	await mkdir(dirname(file), { recursive: true });
	await writeFile(file, `${HEADER}\nexport default function Footer() @{\n${toTsrx([footer], 1)}}\n`);
}

// Each page boots the theme's script (lib/site.ts), or the debug panel's own (lib/debug-panel.ts).
const BOOTS = { site: ['siteBoot', 'lib/site.ts'], debug: ['debugBoot', 'lib/debug-panel.ts'] };

export async function writePage(path, file, body, boot = 'site') {
	const root = body[0];
	let footer;
	const children = root.children.map((child) => {
		if (!isFooter(child)) return child;
		footer = child;
		return { expression: '<Footer />' };
	});
	const rel = (target) => relative(dirname(file), join(app, target)).split('\\').join('/');
	const [bootName, bootFile] = BOOTS[boot];
	const imports = [`import { ${bootName} } from '${rel(bootFile)}';`, ...(footer ? [`import Footer from '${rel('components/generated/footer.tsrx')}';`] : [])];
	// The site's script also boots on a click, and handles that click: one made before it loaded is not lost.
	const triggers = ` onVisible={() => ${bootName}()} onIdle={() => ${bootName}()}${boot === 'site' ? ` onClick={(event) => ${bootName}(event)}` : ''}`;
	const markup = toTsrx([{ ...root, children }], 1, { extra: (node) => (node === root || node.children === children ? triggers : '') });
	await mkdir(dirname(file), { recursive: true });
	await writeFile(file, `${HEADER} (${path})\n${imports.join('\n')}\n\nexport default function Page() @{\n${markup}}\n`);
	return footer;
}

// The HTML files in the old site's static directories, which it serves as pages of their own (no Docusaurus around
// them) at `/x` and `/x.html`, or `/dir` and `/dir/index.html`. Each becomes a Markless page at the first address with
// the file's body, and document.tsrx writes the file's own <head> for it instead of the theme's; the file's own
// address is served from that page by a route rule (lib/route-aliases.json).
export async function staticHtmlPages(site) {
	const pages = [];
	for (const dir of site.context.siteConfig.staticDirectories) {
		const root = join(website, dir.startsWith('/') ? relative(website, dir) : dir);
		const walk = async (at) => {
			for (const entry of await readdir(at, { withFileTypes: true }).catch(() => [])) {
				const full = join(at, entry.name);
				if (entry.isDirectory()) await walk(full);
				else if (entry.name.endsWith('.html')) {
					const file = `/${relative(root, full).split('\\').join('/')}`;
					const document = parseDocument(await readFile(full, 'utf8'));
					const part = (tag) => document.children.find((n) => typeof n !== 'string' && n.tag === tag)?.children ?? [];
					// mm-site.css: the router's wrapper around the page takes no box, as on every other page.
					const head = [...part('head').filter((n) => typeof n !== 'string'), { tag: 'link', attrs: [['rel', 'stylesheet'], ['href', '/mm-site.css']], children: [] }];
					const body = part('body');
					const bare = file.endsWith('/index.html') ? file.slice(0, -'/index.html'.length) : file.slice(0, -'.html'.length);
					pages.push({ path: bare, file, head, body });
				}
			}
		};
		await walk(root);
	}
	return pages;
}

