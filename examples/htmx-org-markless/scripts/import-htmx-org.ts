for (const route of routes) {
	const builtFile = route === '/404/' ? join(site, '404.html') : join(site, route, 'index.html');
	const built = readFileSync(builtFile, 'utf8');
	const document = parse(built);
	const head = find(document, (el) => el.tagName === 'head')!;
	const headElements = elements(head);
	const description = attr(headElements.find((el) => el.tagName === 'meta' && attr(el, 'name') === 'description'), 'content') ?? '';
	const alternates = [...headElements, ...elements(find(document, (el) => el.tagName === 'body')!)]
		.filter((el) => el.tagName === 'link' && attr(el, 'rel') === 'alternate' && attr(el, 'href') !== '/atom.xml')
		.map((el) => ({ type: attr(el, 'type') ?? '', title: attr(el, 'title') ?? '', href: attr(el, 'href') ?? '' }));
	// A description with a raw quote (hx-partial's) ends <head> early in HTML parsing; the title and links after it still count.
	const titleElement = find(document, (el) => el.tagName === 'title');
	const libraries: Libraries = { htmx: false, classTools: false, preload: false, hyperscript: false };

	const content = readFileSync(route === '/404/' ? join(overlay, '404.html') : join(overlay, route, 'index.html'), 'utf8');
	const metaJson = /<script id="zola-meta" type="application\/json">([\s\S]*?)<\/script>/.exec(content)?.[1];
	if (!metaJson) throw new Error(`${route}: the content build has no front matter`);
	const meta = JSON.parse(metaJson) as Meta;
	const template = TEMPLATES[meta.template];
	if (!template) throw new Error(`${route}: no importer for Zola template ${meta.template}`);
	const inner = template(meta, innerHtml(content, 'zola-content'));
	const ours = normalized(inner);
	const theirs = normalized(mainInner(built));
	const items = (html: string) => html.split('<li>').sort().join('<li>');
	if (ours !== theirs && items(ours) === items(theirs)) console.warn(`${route}: list items in another order than this Zola build (ties among equal dates)`);
	else if (ours !== theirs) {
		let i = 0;
		while (ours[i] === theirs[i]) i++;
		mismatches.push(`${route}\n  ours:   …${ours.slice(Math.max(0, i - 60), i + 60)}\n  zola's: …${theirs.slice(Math.max(0, i - 60), i + 60)}`);
	}
	// A demo page whose content runs nothing (no script, no htmx or hyperscript attribute outside its code samples) has no
	// demo: the template's sinon and demo.js only make buttons.js fall back to its iframe (SiteHeader starFrame), so the
	// page loads neither them nor htmx.
	const bare: Libraries = { htmx: false, classTools: false, preload: false, hyperscript: false };
	const noDemo = meta.template === 'demo' && !/<script\b/.test(convert(innerHtml(content, 'zola-content'), bare).tsrx) && !Object.values(bare).some(Boolean);
	let converted = convert(noDemo ? inner.replace(DEMO_SCRIPTS, '') : inner, libraries);
	if (meta.template === 'demo' && !noDemo) libraries.htmx = true;
	// class-tools with nothing else of htmx (hx-indicator's demo): lib/class-tools.ts runs it, and no htmx loads.
	if (libraries.classTools && !libraries.htmx) {
		converted = convert(inner, { ...libraries }, { portClassTools: true });
		libraries.classTools = false;
	}
	for (const d of converted.dropped) console.warn(`${route}: dropped attribute ${d} (malformed markup in the source)`);

	// The page's header, main and footer sit in Markless Router's route container, not directly in <body>.
	const stylesheets = converted.styles.map((source) => {
		const css = source.replace(/\bbody\s*>\s*/g, 'body > [data-async-container] > div > ');
		const name = `/css/port/${createHash('sha256').update(css).digest('hex').slice(0, 10)}.css`;
		styleFiles.set(name, css);
		return name;
	});
	const scripts = [
		libraries.htmx && '/js/htmx.js',
		libraries.classTools && '/js/class-tools.js',
		libraries.preload && '/js/preload.js',
		libraries.hyperscript && '/js/_hyperscript.js',
	].filter((s): s is string => !!s);
	const hand = HAND_PORTED.has(route);
	const served = route.toLowerCase();
	if (served !== route) netlify[route] = { status: 301, location: served };
	heads[served] = {
		title: titleElement ? textOf(built.slice(built.indexOf('<title>'), built.indexOf('</title>') + 8)) : '',
		description,
		canonical: attr(find(document, (el) => el.tagName === 'link' && attr(el, 'rel') === 'canonical'), 'href'),
		alternates,
		stylesheets: HAND_PORTED.get(route) ?? stylesheets,
		scripts: hand ? [] : scripts,
	};
	if (hand) continue;

	const classes = String(meta.extra.custom_classes ?? '');
	if (classes !== '' && classes !== 'wide-content') throw new Error(`${route}: custom_classes ${classes} has no footer variant`);
	const internal = RESERVED.test(served) ? `/_${served.slice(1)}` : served;
	if (internal !== served) renamed[served] = internal;
	const file = route === '/404/' ? join(APP, 'pages', '404.tsrx') : join(APP, 'pages', internal, 'index.tsrx');
	const up = relative(dirname(file), APP) || '.';
	const indent = (text: string, tabs: string) => text.split('\n').map((line) => tabs + line).join('\n');
	mkdirSync(dirname(file), { recursive: true });
	const handles = converted.handles;
	writeFileSync(
		file,
		`${GENERATED}
${handles.length ? `import { element } from '@markless/core';\n` : ''}import SiteFooter from '${up}/components/site-footer.tsrx';
import SiteHeader from '${up}/components/site-header.tsrx';
${handles.length ? `import { runClassTools } from '${up}/lib/class-tools.ts';\n` : ''}${converted.copiesText ? `import { copyPrevious } from '${up}/lib/copy-text.ts';\n` : ''}${converted.filtersExtensions ? `import { clearExtensionFilter, filterExtensions } from '${up}/lib/extension-filter.ts';\n` : ''}
export default function Page() @{
${handles.map((h) => `\tconst ${h} = element<HTMLElement>();\n`).join('')}	<div style="display: contents">
		<SiteHeader${noDemo ? ' starFrame' : ''} />
		<main class="c content ${classes}">
${indent(converted.tsrx, '\t\t\t')}
		</main>
		<SiteFooter${classes ? ' wide' : ''} />
	</div>
}
`,
	);
	generated.add(file);
}

