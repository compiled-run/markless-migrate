const run = (cmd: string, argv: string[], cwd?: string) => execFileSync(cmd, argv, { cwd, stdio: ['ignore', 'pipe', 'inherit'] }).toString();

function source(): string {
	if (sourceArg) return sourceArg;
	const dir = join(WORK, 'htmx');
	if (!existsSync(join(dir, '.git'))) {
		mkdirSync(WORK, { recursive: true });
		run('git', ['clone', '--quiet', '--filter=blob:none', '--no-checkout', SOURCE_REPO, dir]);
	}
	if (run('git', ['rev-parse', 'HEAD'], dir).trim() !== SOURCE_COMMIT) run('git', ['fetch', '--quiet', 'origin', SOURCE_COMMIT], dir);
	if (run('git', ['status', '--porcelain'], dir) || !existsSync(join(dir, 'netlify.toml'))) run('git', ['checkout', '--quiet', '--force', SOURCE_COMMIT], dir);
	return dir;
}

function zola(repo: string): string {
	const version = /ZOLA_VERSION\s*=\s*"([^"]+)"/.exec(readFileSync(join(repo, 'netlify.toml'), 'utf8'))?.[1];
	if (!version) throw new Error('netlify.toml names no ZOLA_VERSION');
	const bin = join(WORK, `zola-${version}`, 'zola');
	if (existsSync(bin)) return bin;
	const arch = process.arch === 'arm64' ? 'aarch64' : 'x86_64';
	const triple = process.platform === 'darwin' ? `${arch}-apple-darwin` : `${arch}-unknown-linux-gnu`;
	mkdirSync(dirname(bin), { recursive: true });
	const tarball = join(dirname(bin), 'zola.tar.gz');
	run('curl', ['-fsSL', '-o', tarball, `https://github.com/getzola/zola/releases/download/v${version}/zola-v${version}-${triple}.tar.gz`]);
	run('tar', ['xzf', tarball, '-C', dirname(bin)]);
	return bin;
}

function walk(dir: string, files: string[] = []): string[] {
	for (const name of readdirSync(dir)) {
		const path = join(dir, name);
		if (statSync(path).isDirectory()) walk(path, files);
		else files.push(path);
	}
	return files;
}

function find(parent: ParentNode, test: (el: Element) => boolean): Element | undefined {
	for (const child of parent.childNodes) {
		if (!('tagName' in child)) continue;
		if (test(child)) return child;
		const inner = find(child, test);
		if (inner) return inner;
	}
	return undefined;
}
const attr = (el: Element | undefined, name: string) => el?.attrs.find((a) => a.name === name)?.value;
const elements = (parent: ParentNode): Element[] => parent.childNodes.filter((n): n is Element => 'tagName' in n);

function innerHtml(html: string, id: string): string {
	const start = html.indexOf(`<div id="${id}">`);
	const end = html.lastIndexOf('</div>');
	if (start < 0 || end < start) throw new Error(`no #${id} in the content build`);
	return html.slice(start + `<div id="${id}">`.length, end);
}

function mainInner(html: string): string {
	const start = html.indexOf('>', html.indexOf('<main')) + 1;
	return html.slice(start, html.lastIndexOf('</main>'));
}

