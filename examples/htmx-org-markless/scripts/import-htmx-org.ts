// Everything else Zola writes is served as it is: static files, feeds, sitemap, robots.txt, alias pages, 404.html.
const pagesServed = new Set(routes.filter((r) => r !== '/404/').map((r) => join(site, r, 'index.html')));
const publicDir = join(WORK, 'public');
rmSync(publicDir, { recursive: true, force: true });
let staticCount = 0;
for (const file of walk(site)) {
	if (pagesServed.has(file) || file === join(site, '_redirects')) continue;
	const target = join(publicDir, relative(site, file));
	mkdirSync(dirname(target), { recursive: true });
	if (file.endsWith('.html')) writeFileSync(target, prettyLinks(readFileSync(file, 'utf8'), `/${relative(site, file)}`));
	else cpSync(file, target);
	staticCount++;
	const path = `/${relative(site, file)}`;
	if (!path.endsWith('.html')) continue;
	if (path.endsWith('/index.html')) {
		netlify[path.slice(0, -'index.html'.length)] ??= { dest: path };
		continue;
	}
	const pretty = path.slice(0, -'.html'.length).toLowerCase();
	netlify[pretty] = { dest: path };
	if (path !== path.toLowerCase()) netlify[path] = { status: 301, location: pretty };
}
for (const route of routes) if (route !== '/404/') netlify[`${route.toLowerCase()}index.html`] = { dest: route.toLowerCase() };
// Netlify finds a file whatever the case of its path; pages here ask for /img/Github_Logo.png, the file is GitHub_Logo.png.
const byLowerCase = new Map(walk(publicDir).map((f) => [`/${relative(publicDir, f)}`.toLowerCase(), `/${relative(publicDir, f)}`]));
for (const route of routes) {
	const html = readFileSync(route === '/404/' ? join(site, '404.html') : join(site, route, 'index.html'), 'utf8');
	for (const [, path] of html.matchAll(/(?:src|href)=["']?(\/[^"' >?#]+)/g)) {
		const file = byLowerCase.get(path!.toLowerCase());
		if (file && file !== path && !netlify[path!]) netlify[path!] = { dest: file };
	}
}

// Netlify's _redirects (default status 301, with or without the trailing slash); the demo.htmx.org host rule has no
// counterpart on this host.
for (const line of readFileSync(join(site, '_redirects'), 'utf8').split('\n')) {
	const [from, to, status] = line.trim().split(/\s+/);
	if (!from || !to || !from.startsWith('/')) continue;
	for (const path of new Set([from, from.endsWith('/') ? from.slice(0, -1) : `${from}/`])) netlify[path] = { status: Number.parseInt(status ?? '301', 10), location: to };
}
writeFileSync(join(APP, 'internal-paths.ts'), `${GENERATED}\n// Public path -> the path its page file is routed at.\nexport const INTERNAL_PATHS: Record<string, string> = ${JSON.stringify(renamed, null, '\t')};\n`);
writeFileSync(
	join(APP, 'netlify-routes.ts'),
	`${GENERATED}
// What Netlify answers for htmx.org beyond its files: _redirects, Pretty URLs (/x serves x.html, /x/index.html serves
// /x/), and a 301 to the lower-case path for an HTML path with capitals. Exact, case-sensitive paths.
export type NetlifyRoute = { readonly status: number; readonly location: string } | { readonly dest: string };
export const NETLIFY_ROUTES: Record<string, NetlifyRoute> = ${JSON.stringify(netlify, null, '\t')};
`,
);
for (const [name, css] of styleFiles) {
	mkdirSync(dirname(join(publicDir, name)), { recursive: true });
	writeFileSync(join(publicDir, name), css);
}

console.log(`${routes.length - 1} sitemap routes: ${generated.size} pages generated, ${HAND_PORTED.size} ported by hand; ${staticCount} static files, ${Object.keys(netlify).length} Netlify routes`);
if (mismatches.length) {
	console.error(`Text differs from htmx.org's own build of the page:\n${mismatches.join('\n')}`);
	process.exitCode = 1;
}
