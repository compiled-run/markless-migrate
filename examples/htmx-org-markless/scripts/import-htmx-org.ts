// Netlify's Pretty URLs rewrite a static page's links to other .html files into lower-case paths without the extension,
// writing the tag again with href first and every value in single quotes.
function prettyLinks(html: string, path: string): string {
	return html.replace(/<a\b([^>]*)>/gi, (tag, inside: string) => {
		const attrs = [...inside.matchAll(/([^\s=]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g)].map((m) => [m[1]!, m[2] ?? m[3] ?? ''] as const);
		const href = attrs.find(([name]) => name.toLowerCase() === 'href')?.[1];
		const link = href && /^([^#?:]+\.html)([?#].*)?$/.exec(href);
		if (!link) return tag;
		const absolute = new URL(link[1]!, `http://x${path}`).pathname.toLowerCase();
		const pretty = (absolute.endsWith('/index.html') ? absolute.slice(0, -'index.html'.length) : absolute.slice(0, -'.html'.length)) + (link[2] ?? '');
		return `<a href='${pretty}'${attrs.filter(([name]) => name.toLowerCase() !== 'href').map(([name, value]) => ` ${name}='${value}'`).join('')}>`;
	});
}

// Pages generated by an earlier run go first: a route may have gone, or changed only in case (macOS keeps the old name).
function prune(dir: string) {
	for (const name of readdirSync(dir)) {
		const path = join(dir, name);
		if (statSync(path).isDirectory()) {
			prune(path);
			if (readdirSync(path).length === 0) rmSync(path, { recursive: true });
		} else if (readFileSync(path, 'utf8').startsWith(GENERATED)) rmSync(path);
	}
}
