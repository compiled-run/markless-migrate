// The alpinejs.dev pages with no open source, from content/server-pages (importer/capture-server-pages.ts): one rule
// per template (component page, /components, /license, the guest pages /login and /forgot-password). Run on its own
// (node importer/server-pages.ts) or call generateServerPages().
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { attribute, emitNodes, htmlToTsrx, lit, type Element, type Node } from './tsrx.ts';
import { write } from './write.ts';

const GENERATED = '// Generated by importer/server-pages.ts from content/server-pages; edit the importer or the capture, not this file.\n';

const APP = join(import.meta.dirname, '..');
const read = <T>(name: string): T => JSON.parse(readFileSync(join(APP, 'content/server-pages', `${name}.json`), 'utf8')) as T;
const out = (path: string) => join(APP, path);

interface Head {
	readonly title: string;
	readonly description: string;
	readonly ogImage: string;
	readonly stylesheets: readonly string[];
	readonly styles: readonly string[];
}
interface ComponentLayout {
	readonly sections: readonly { title: string; headingClass: string; listClass: string; items: readonly { href: string; label: string }[] }[];
	readonly linkClass: string;
	readonly activeLinkClass: string;
	readonly skeleton: string;
}
interface ComponentPage {
	readonly route: string;
	readonly head: Head;
	readonly title: string;
	readonly column: string;
	readonly demos: number;
	readonly dialog: string;
}

const attr = (el: Element, name: string) => el.attrs.find((a) => a.name === name)?.value;
const PORT = /^data-port-/;
const ownAttrs = (el: Element) => el.attrs.filter((a) => !PORT.test(a.name)).map((a) => attribute(a.name, a.value)).join('');

// Writes an element with extra props in place of its data-port-* notes, its children through the same rules.
function element(el: Element, depth: number, extra: string, rules: (el: Element, depth: number) => string | undefined): string {
	const pad = '\t'.repeat(depth);
	if (el.tagName === 'input' || el.tagName === 'img') return `${pad}<${el.tagName}${ownAttrs(el)}${extra} />\n`;
	const body = emitNodes(el.childNodes as Node[], depth + 1, { element: rules }, el);
	return `${pad}<${el.tagName}${ownAttrs(el)}${extra}>\n${body}${pad}</${el.tagName}>\n`;
}

const OPEN_AUTH = `onClick={(event) => { event.preventDefault(); openAuth(); }}`;

// The sign-in dialog. Its notes (from Alpine's directives) become: x-show groups that show and hide with Alpine's own
// transitions (components/ui-transition.ts), Escape and the backdrop closing it, the trap that keeps focus inside
// and hides and stills the page behind, the register toggle, and a form that cannot post (no backend).
function dialogComponent(name: string, html: string): string {
	const handles: string[] = [];
	const groups = new Map<string, string[]>();
	let root = '';
	let box = '';
	const handle = (el: Element) => {
		const id = `el${handles.length}`;
		handles.push(id);
		return id;
	};
	const state = JSON.parse(/data-port-state="([^"]*)"/.exec(html)?.[1]?.replace(/&quot;/g, '"') ?? '{"registering":false}') as { registering: boolean };
	const initial: Record<string, boolean> = { open: false, '!open': true, registering: state.registering, '!registering': !state.registering };
	const group = (expression: string) => `[${(groups.get(expression) ?? []).join(', ')}]`;
	const rules = (el: Element, depth: number): string | undefined => {
		if (!el.attrs.some((a) => PORT.test(a.name)) && el.tagName !== 'form') return undefined;
		const props: string[] = [];
		let id: string | undefined;
		const need = () => (id ??= handle(el));
		const show = attr(el, 'data-port-show');
		if (show) {
			const transition = attr(el, 'data-port-transition');
			(groups.get(show) ?? groups.set(show, []).get(show)!).push(`{ el: ${need()}${transition ? `, transition: ${lit(transition)} as const` : ''} }`);
			if (initial[show] === false && !/display:\s*none/.test(attr(el, 'style') ?? '')) el.attrs.push({ name: 'style', value: `${attr(el, 'style') ? `${attr(el, 'style')}; ` : ''}display: none;` });
		}
		if (attr(el, 'role') === 'dialog') {
			root = need();
			const escape = attr(el, 'data-port-escape') !== undefined;
			props.push(`onKeyDown={(event) => { ${escape ? "if (event.key === 'Escape') { event.preventDefault(); event.stopPropagation(); CLOSE } else " : ''}if (event.key === 'Tab') keepFocusInside(event, BOX); }}`);
		}
		if (attr(el, 'data-port-trap') !== undefined) box = need();
		const click = attr(el, 'data-port-click');
		if (click === 'close') props.push(`onClick={(event) => { if (BOX && BOX.contains(event.target as Node)) return; CLOSE }}`);
		if (click === 'close prevent') props.push(`onClick={(event) => { event.preventDefault(); CLOSE }}`);
		if (click === 'toggle-registering prevent') props.push(`onClick={(event) => { event.preventDefault(); registering = !registering; toggle(G(registering), registering); toggle(G(!registering), !registering); }}`);
		if (click === 'open-auth') props.push(OPEN_AUTH);
		if (el.tagName === 'form') props.push(`onSubmit={(event) => event.preventDefault()}`);
		if (id) props.unshift(`el={${id}}`);
		return element(el, depth, props.length ? ` ${props.join(' ')}` : '', rules);
	};
	let body = htmlToTsrx(html, 1, { element: rules });
	if (!root || !box) throw new Error(`${name}: the dialog has no root or no trapped box`);
	const close = `if (!open) return; open = false; closeTrap(); toggle(G(open), false);`;
	body = body.replaceAll('CLOSE', close).replaceAll('BOX', box);
	body = body.replace(/G\((!?)(open|registering)\)/g, (_, not: string, v: string) => group(`${not}${v}`));
	const open = `if (open) return; open = true; toggle(${group('open')}, true); setTimeout(() => requestAnimationFrame(() => requestAnimationFrame(() => openTrap(${box}))), 15);`;
	body = body.replace(` el={${root}} onKeyDown=`, ` el={${root}} onIdle={() => { const show = () => { ${open} }; window.addEventListener(AUTH_EVENT, show); if (takePendingAuth()) show(); }} onKeyDown=`);
	return `${GENERATED}import { element, state } from '@markless/core';
import { toggle } from './ui-transition.ts';
import { openTrap, closeTrap, keepFocusInside } from './trap.ts';
import { AUTH_EVENT, takePendingAuth } from './ui-auth.ts';

export default function ${name}() @{
	let open = state(false);
	let registering = state(${state.registering});
${handles.map((h) => `\tconst ${h} = element<HTMLElement>();`).join('\n')}

${body}}
`;
}

const dialogs = new Map<string, string>();
// Identical dialogs share one component.
function dialogFor(html: string): string {
	const key = html.replace(/\s+/g, ' ');
	if (!dialogs.has(key)) {
		const name = `UiAuthDialog${dialogs.size || ''}`;
		dialogs.set(key, name);
		write(out(`components/${kebab(name)}.tsrx`), dialogComponent(name, html));
	}
	return dialogs.get(key)!;
}
const kebab = (name: string) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

const LINK_CLASS = 'text-sm text-gray-500 underline hover:text-gray-700';

// A page body: data-port notes on page elements (the buttons that open the dialog) and the layout's slots.
function pageBody(html: string, depth: number, slots: Record<string, (el: Element, depth: number) => string>): string {
	const rules = (el: Element, d: number): string | undefined => {
		if (el.tagName === 'port-slot') return slots[attr(el, 'name')!]!(el, d);
		if (attr(el, 'data-port-click') === 'open-auth') return element(el, d, ` ${OPEN_AUTH}`, rules);
		if (el.attrs.some((a) => PORT.test(a.name))) throw new Error(`no page rule for ${el.attrs.map((a) => a.name).join(' ')}`);
		return undefined;
	};
	return htmlToTsrx(html, depth, { element: rules });
}

const imports = (...lines: string[]) => lines.filter(Boolean).join('\n');

export function generateServerPages(): { routes: string[] } {
	const routes: string[] = [];
	const heads: string[] = [];
	const addHead = (route: string, head: Head) => {
		heads.push(`\t${lit(route)}: { title: ${lit(head.title)}, description: ${lit(head.description)}, image: ${lit(head.ogImage)} },`);
		routes.push(route);
	};

	// Component pages: the layout's skeleton around each page's column; the sidebar marks the page's own link.
	const layout = read<ComponentLayout>('component-layout');
	const sidebar = `${GENERATED}export default function UiComponentSidebar({ pathname, class: className }: { readonly pathname: string; readonly class: string }) @{
	<nav class={className}>
${layout.sections
	.map(
		(section) => `\t\t<h3 class=${lit(section.headingClass)}>${section.title}</h3>
		<ul class=${lit(section.listClass)}>
${section.items.map((item) => `\t\t\t<li>
				<a href=${lit(item.href)} class={pathname === ${lit(new URL(item.href, 'https://alpinejs.dev').pathname)} ? ${lit(layout.activeLinkClass)} : ${lit(layout.linkClass)}}>${item.label}</a>
			</li>`).join('\n')}
		</ul>`,
	)
	.join('\n')}
	</nav>
}
`;
	write(out('components/ui-component-sidebar.tsrx'), sidebar);
	for (const page of read<ComponentPage[]>('component-pages')) {
		addHead(page.route, page.head);
		const dialog = dialogFor(page.dialog);
		const original = `https://alpinejs.dev${page.route}`;
		const column = (el: Element, depth: number) =>
			pageBody(page.column, depth, {
				demo: (_el, d) => `${'\t'.repeat(d)}<a href=${lit(original)} class=${lit(LINK_CLASS)}>Open this demo on alpinejs.dev</a>\n`,
				code: (_el, d) => `${'\t'.repeat(d)}<div class="px-5 py-8 text-center"><a href=${lit(original)} class=${lit(LINK_CLASS)}>Open the code on alpinejs.dev</a></div>\n`,
			});
		const body = pageBody(layout.skeleton, 1, {
			sidebar: (el, d) => `${'\t'.repeat(d)}<UiComponentSidebar pathname={url.pathname} class=${lit(attr(el, 'class')!)} />\n`,
			column,
			dialog: (_el, d) => `${'\t'.repeat(d)}<${dialog} />\n`,
		}).replace(/\n\t<\/div>\n$/, '\n\t\t<Attribution />\n\t</div>\n');
		write(
			out(`pages${page.route}.tsrx`),
			`${GENERATED}${imports(
				`import type { PageProps } from '@markless/router';`,
				`import UiComponentSidebar from '../../components/ui-component-sidebar.tsrx';`,
				`import ${dialog} from '../../components/${kebab(dialog)}.tsrx';`,
				`import Attribution from '../../components/attribution.tsrx';`,
				/openAuth\(\)/.test(body) ? `import { openAuth } from '../../components/ui-auth.ts';` : '',
			)}

export default function ComponentPage({ url }: PageProps) @{
${body}}
`,
		);
	}

	// /components: the marketing page and its dialog.
	{
		const page = read<{ route: string; head: Head; body: string; dialog: string }>('components');
		addHead(page.route, page.head);
		const dialog = dialogFor(page.dialog);
		const body = pageBody(page.body, 1, { dialog: (_el, d) => `${'\t'.repeat(d)}<${dialog} />\n` }).replace(/\n\t<\/div>\n$/, '\n\t\t<Attribution />\n\t</div>\n');
		write(
			out('pages/components.tsrx'),
			`${GENERATED}${imports(
				`import ${dialog} from '../components/${kebab(dialog)}.tsrx';`,
				`import Attribution from '../components/attribution.tsrx';`,
				/openAuth\(\)/.test(body) ? `import { openAuth } from '../components/ui-auth.ts';` : '',
			)}

export default function Components() @{
${body}}
`,
		);
	}

	// /license: the docs layout (header, sidebar, contents column, sponsor, contents list) around the license text.
	{
		const page = read<{ route: string; head: Head; content: string }>('license');
		addHead(page.route, page.head);
		write(
			out('pages/license.tsrx'),
			`${GENERATED}import type { PageProps } from '@markless/router';
import DocsHeader from '../components/docs-header.tsrx';
import DocsSidebar from '../components/docs-sidebar.tsrx';
import Sponsor from '../components/sponsor.tsrx';
import Toc from '../components/toc.tsrx';
import Attribution from '../components/attribution.tsrx';

const HEADINGS = [] as const;

export default function License({ url }: PageProps) @{
	<div style="display: contents">
		<DocsHeader pathname={url.pathname} />
		<DocsSidebar pathname={url.pathname} />
		<main class="pt-32 pl-0 pr-0 md:pl-48 lg:pl-64 xl:pr-64">
			<div class="m-auto max-w-3xl px-6 pb-24 text-gray-800 antialiased markdown" listen-for-intersection-of-titles="">
${htmlToTsrx(page.content, 4)}				<Sponsor wrapper="my-12 border-y border-gray-200 py-6 xl:hidden" label="mb-3 block text-xs font-semibold uppercase tracking-wider text-gray-400" />
				<div class="flex justify-between border-t border-gray-200 pt-4 text-gray-700">
					<div></div>
					<div></div>
				</div>
				<p class="mt-6 text-center text-sm text-gray-600">Code highlighting provided by <a href="https://torchlight.dev" target="__blank" class="font-semibold text-cyan-400">Torchlight</a></p>
				<div class="mt-6 flex items-center justify-center gap-4 text-center text-sm text-gray-600"></div>
				<Attribution />
			</div>
		</main>
		<Toc headings={HEADINGS} />
	</div>
}
`,
		);
	}

	// /login and /forgot-password: the guest layout; their forms have no backend to post to, so submitting does nothing.
	for (const name of ['login', 'forgot-password']) {
		const page = read<{ route: string; head: Head; body: string }>(name);
		addHead(page.route, page.head);
		const rules = (el: Element, depth: number): string | undefined => (el.tagName === 'form' ? element(el, depth, ` onSubmit={(event) => event.preventDefault()}`, rules) : undefined);
		const nodes = htmlToTsrx(page.body, 2, { element: rules });
		write(
			out(`pages/${name}.tsrx`),
			`${GENERATED}import Attribution from '../components/attribution.tsrx';

export default function Guest() @{
	<div style="display: contents">
${nodes}		<Attribution />
	</div>
}
`,
		);
	}

	// What each template adds to the document head beyond the docs pages' own.
	const inter = read<ComponentPage[]>('component-pages')[0]!.head;
	const interCss = inter.stylesheets.find((href) => href.includes('inter'))!;
	write(out('public/port/ui-components.css'), `/* From the inline <style> the component pages add to their head. */\n${inter.styles.join('\n')}\n`);
	const interRoutes = routes.filter((r) => r.startsWith('/component/') || r === '/components');
	write(
		out('generated/server-heads.ts'),
		`${GENERATED}import type { Head } from '../site.ts';

export const SERVER_HEADS: Readonly<Record<string, Head>> = {
${heads.join('\n')}
};

export const SERVER_ROUTES: readonly string[] = ${JSON.stringify(routes)};

const INTER = new Set(${JSON.stringify(interRoutes)});
const DOCS_LAYOUT = new Set(['/license']);

// The stylesheets a server page's head adds: the component pages and /components load Inter and its heading rule;
// /license uses the docs layout's styles; /login and /forgot-password neither.
export function serverStylesheets(pathname: string): readonly string[] | undefined {
	if (INTER.has(pathname)) return [${lit(interCss)}, '/port/ui-components.css'];
	if (DOCS_LAYOUT.has(pathname)) return ['/port/docs.css'];
	if (${JSON.stringify(routes)}.includes(pathname)) return [];
	return undefined;
}
`,
	);
	return { routes };
}

if (import.meta.main) {
	const { routes } = generateServerPages();
	console.log(`server pages: ${routes.length} routes`);
}
