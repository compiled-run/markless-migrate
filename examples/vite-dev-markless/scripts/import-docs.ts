// VitePress's head for a page: the site head with the page's frontmatter head merged in, then the config's
// transformHead (canonical and og:title); a meta tag of the same name or property replaces the earlier one in place.
function headOf(route: string, page: { title: string; description: string; frontmatter: Record<string, unknown> }, relativePath: string): Head {
	const entries: [string, Record<string, string>][] = [];
	const key = ([tag, attrs]: [string, Record<string, string>]) =>
		tag === 'meta' ? `meta:${attrs.name ?? attrs.property}` : tag === 'link' && attrs.rel === 'canonical' ? 'canonical' : undefined;
	const add = (entry: [string, Record<string, string>]) => {
		const k = key(entry);
		const at = k ? entries.findIndex((e) => key(e) === k) : -1;
		if (at >= 0) entries[at] = entry;
		else entries.push(entry);
	};
	for (const entry of siteConfig.site.head) add(entry);
	for (const entry of (page.frontmatter.head as [string, Record<string, string>][] | undefined) ?? []) add(entry);
	const path = relativePath.replace(/(^|\/)index\.md$/, '$1').replace(/\.md$/, '');
	if (path !== '404') {
		add(['link', { rel: 'canonical', href: path ? `https://vite.dev/${path}` : 'https://vite.dev' }]);
		add(['meta', { property: 'og:title', content: page.title }]);
	}
	const template = (page.frontmatter.titleTemplate as string | undefined) ?? `:title | ${site.title}`;
	const markdown = `${route === '/' ? '/index' : route.replace(/\/$/, '')}.md`;
	return {
		title: page.title ? template.replace(':title', page.title) : 'Vite',
		description: page.description || site.description,
		meta: entries.filter(([tag]) => tag === 'meta').map(([, attrs]) => attrs),
		links: entries.filter(([tag]) => tag === 'link').map(([, attrs]) => attrs),
		...(existsSync(join(APP, 'public', markdown)) ? { markdown } : {}),
	};
}

function writePage(file: string, body: string): void {
	const imports = new Map<string, string>();
	const converted = convert(body, {
		asset: (value, name) => {
			if (!/^(src|href|xlink:href|poster)$/.test(name)) return undefined;
			if (!value.startsWith('/')) return undefined;
			const found = assetFile(value);
			if (!found) return undefined;
			copyAsset(found.file);
			let rel = relative(dirname(file), found.file);
			if (!rel.startsWith('.')) rel = `./${rel}`;
			return { specifier: rel, suffix: found.suffix };
		},
	});
	for (const [specifier, name] of converted.imports) imports.set(name, specifier);
	const used = (name: string) => converted.tsrx.includes(`<${name} `) || converted.tsrx.includes(`<${name}>`);
	const up = relative(dirname(file), APP) || '.';
	const components = [
		['DocsTopBanner', 'components/docs/top-banner.tsrx'],
		['DocsHeader', 'components/docs/header.tsrx'],
		['TopBanner', 'components/top-banner.tsrx'],
		['Header', 'components/header.tsrx'],
		['YouTubeEmbed', 'components/embeds/youtube-embed.tsrx'],
	].filter(([name]) => used(name!));
	const lines = [
		GENERATED,
		...components.map(([name, path]) => `import ${name} from '${up}/${path}';`),
		...[...imports].map(([name, specifier]) => `import ${name} from '${specifier}';`),
		...(body.includes('&quot;$expression&quot;:&quot;url.pathname&quot;')
			? ["import type { PageProps } from '@markless/router';", '', 'export default function Page({ url }: PageProps) @{']
			: ['', 'export default function Page() @{']),
		converted.tsrx
			.split('\n')
			.map((line) => `\t${line}`)
			.join('\n'),
		'}',
		'',
	];
	mkdirSync(dirname(file), { recursive: true });
	writeFileSync(file, lines.join('\n'));
}

