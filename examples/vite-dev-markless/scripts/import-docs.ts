type Element = DefaultTreeAdapterMap['element'];
type ParentNode = DefaultTreeAdapterMap['parentNode'];
const isElement = (n: DefaultTreeAdapterMap['childNode']): n is Element => 'tagName' in n;
const textContent = (n: DefaultTreeAdapterMap['childNode']): string =>
	n.nodeName === '#text' ? (n as DefaultTreeAdapterMap['textNode']).value : isElement(n) ? n.childNodes.map(textContent).join('') : '';
const attrOf = (el: Element, name: string) => el.attrs.find((a) => a.name === name)?.value;

// The theme's getHeaders() over the rendered page: headings with an id, titled without badges and anchors, kept
// within the outline's levels and nested by level (outline.ts's resolveHeaders and buildTree).
function headers(html: string, range: unknown): OutlineItem[] {
	if (range === false) return [];
	const found: { level: number; title: string; link: string; ignore: boolean }[] = [];
	const walk = (parent: ParentNode) => {
		for (const n of parent.childNodes) {
			if (!isElement(n)) continue;
			const level = /^h([1-6])$/.exec(n.tagName)?.[1];
			const id = attrOf(n, 'id');
			if (level && id && n.childNodes.length) {
				let title = '';
				for (const child of n.childNodes) {
					if (isElement(child)) {
						if (/\b(?:VPBadge|header-anchor|footnote-ref|ignore-header)\b/.test(attrOf(child, 'class') ?? '')) continue;
						title += textContent(child);
					} else if (child.nodeName === '#text') title += textContent(child);
				}
				found.push({
					level: Number(level),
					title: title.trim(),
					link: `#${id}`,
					ignore: /\bignore-header\b/.test(attrOf(n, 'class') ?? ''),
				});
			}
			walk(n);
		}
	};
	walk(parseFragment(html));
	const levels = (typeof range === 'object' && range && !Array.isArray(range) ? (range as { level?: unknown }).level : range) || 2;
	const [high, low] = typeof levels === 'number' ? [levels, levels] : levels === 'deep' ? [2, 6] : (levels as [number, number]);
	const result: OutlineItem[] = [];
	const stack: ({ level: number; children: OutlineItem[] } | { level: number; shouldIgnore: true })[] = [];
	for (const item of found) {
		const node = {
			title: item.title,
			link: item.link,
			level: item.level,
			children: [] as OutlineItem[],
		};
		let parent = stack[stack.length - 1];
		while (parent && parent.level >= node.level) {
			stack.pop();
			parent = stack[stack.length - 1];
		}
		if (item.ignore || (parent && 'shouldIgnore' in parent)) {
			stack.push({ level: node.level, shouldIgnore: true });
			continue;
		}
		if (node.level > low || node.level < high) continue;
		if (parent && 'children' in parent) parent.children.push(node);
		else result.push(node);
		stack.push(node);
	}
	return result;
}

// Source assets the dev server serves by path: the build hashes them, so the page imports them and Vite does the same.
const themeAssets = join(dirname(fromDocs.resolve('@voidzero-dev/vitepress-theme/package.json')), 'src/assets');
function assetFile(url: string): { file: string; suffix: string } | undefined {
	const [path, suffix = ''] = url.split(/(?=[?#])/);
	const query = suffix.startsWith('?') ? suffix.replace(/#.*/, '') : '';
	const hash = suffix.includes('#') ? suffix.slice(suffix.indexOf('#')) : '';
	if (path!.startsWith('/@fs/')) {
		const file = path!.slice(4);
		if (file.startsWith(themeAssets)) return { file: join(APP, 'assets', relative(themeAssets, file)) + query, suffix: hash };
		throw new Error(`asset outside the theme: ${url}`);
	}
	if (path!.startsWith('/images/') && existsSync(join(docs!, path!))) return { file: join(APP, 'assets/docs', path!) + query, suffix: hash };
	return undefined;
}
function copyAsset(file: string): void {
	const clean = file.replace(/\?.*$/, '');
	if (existsSync(clean)) return;
	const source = clean.startsWith(join(APP, 'assets/docs')) ? join(docs!, relative(join(APP, 'assets/docs'), clean)) : join(themeAssets, relative(join(APP, 'assets'), clean));
	mkdirSync(dirname(clean), { recursive: true });
	copyFileSync(source, clean);
}

// FloatingVue renders a twoslash popup only while it is shown, so the page carries each one as a <template> in its trigger,
// in place of the hidden popper the server render leaves there; the popups come from the same markdown pipeline.
const md = await vp.createMarkdownRenderer(siteConfig.srcDir, siteConfig.markdown, siteConfig.site.base, siteConfig.logger);
async function popups(relativePath: string): Promise<DefaultTreeAdapterMap['documentFragment'][]> {
	const file = join(siteConfig.srcDir, relativePath);
	if (!existsSync(file)) return [];
	const source = readFileSync(file, 'utf8');
	if (!source.includes('twoslash')) return [];
	const html = await md.renderAsync(
		source.replace(/^---\n[\s\S]*?\n---\n/, (front: string) => '\n'.repeat(front.split('\n').length - 1)),
		{ path: file, relativePath, cleanUrls: true, realPath: file, localeIndex: 'root' },
	);
	const found: DefaultTreeAdapterMap['documentFragment'][] = [];
	const walk = (parent: ParentNode) => {
		for (const n of parent.childNodes) {
			if (!isElement(n)) continue;
			if (n.tagName === 'template' && n.attrs.some((a) => a.name === 'v-slot:popper')) {
				const content = (n as DefaultTreeAdapterMap['template']).content;
				const strip = (p: ParentNode) => {
					for (const c of p.childNodes)
						if (isElement(c)) {
							c.attrs = c.attrs.filter((a) => a.name !== 'v-pre');
							strip(c);
						}
				};
				strip(content);
				found.push(content);
				continue;
			}
			walk(n.tagName === 'template' ? (n as DefaultTreeAdapterMap['template']).content : n);
		}
	};
	walk(parseFragment(html));
	return found;
}
async function withPopups(content: string, relativePath: string): Promise<string> {
	const list = await popups(relativePath);
	if (!list.length) return content;
	const fragment = parseFragment(content);
	let index = 0;
	const walk = (parent: ParentNode) => {
		for (const n of parent.childNodes) {
			if (!isElement(n)) continue;
			if (/\bv-popper__popper\b/.test(attrOf(n, 'class') ?? '')) {
				const popup = list[index++];
				if (!popup) throw new Error(`${relativePath}: more twoslash triggers than popups`);
				const template = parseFragment('<template></template>').childNodes[0] as DefaultTreeAdapterMap['template'];
				template.content = popup;
				template.parentNode = parent;
				parent.childNodes[parent.childNodes.indexOf(n)] = template;
				continue;
			}
			walk(n);
		}
	};
	walk(fragment);
	if (index !== list.length) throw new Error(`${relativePath}: ${list.length} twoslash popups for ${index} triggers`);
	return serialize(fragment);
}

// The theme's YouTubeVideo player frame: components/embeds/youtube-embed.tsrx stands in for it, named after the video
// (its entry in components/embeds/youtube.json), and puts the same frame in its place when a visitor activates it.
function youTubeEmbeds(content: string): string {
	return content.replace(/(<div class="full-width-youtube-video"[^>]*>)<iframe [^>]*\bsrc="(https:\/\/www\.youtube\.com\/embed\/([\w-]+)[^"]*)"[^>]*><\/iframe>/g, (_, wrapper: string, src: string, id: string) => {
		const props = JSON.stringify({ embed: `youtube-${id}`, src: src.replaceAll('&amp;', '&') }).replaceAll('&', '&amp;').replaceAll('"', '&quot;');
		return `${wrapper}<markless-component name="YouTubeEmbed" props="${props}"></markless-component>`;
	});
}

